-- STEP11-2: follow requests/relationships and in-app notifications.
-- Design only: apply in Neon after STEP11-2 review/approval.
-- This migration creates NEW tables and indexes only.
-- Rejected requests may be retried immediately (rejected -> pending via Backend).
-- Read notifications are retained for 30 days after read_at; cleanup is a later job.
-- Existing users/profiles/posts/comments/media/R2 objects are untouched.
BEGIN;

CREATE TABLE public.follows (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  follower_id UUID NOT NULL,
  followee_id UUID NOT NULL,
  status VARCHAR(16) NOT NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_at TIMESTAMPTZ,
  rejected_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT follows_follower_fk
    FOREIGN KEY (follower_id)
    REFERENCES public.users (id)
    ON DELETE CASCADE,

  CONSTRAINT follows_followee_fk
    FOREIGN KEY (followee_id)
    REFERENCES public.users (id)
    ON DELETE CASCADE,

  CONSTRAINT follows_pair_unique UNIQUE (follower_id, followee_id),

  CONSTRAINT follows_no_self_check CHECK (follower_id <> followee_id),

  CONSTRAINT follows_status_check
    CHECK (status IN ('pending', 'accepted', 'rejected')),

  CONSTRAINT follows_timestamp_state_check CHECK (
    (status = 'pending' AND accepted_at IS NULL AND rejected_at IS NULL)
    OR
    (status = 'accepted' AND accepted_at IS NOT NULL AND rejected_at IS NULL)
    OR
    (status = 'rejected' AND accepted_at IS NULL AND rejected_at IS NOT NULL)
  )
);

-- Follower's outgoing list and existing relationship lookups use the UNIQUE index.
-- Followee's incoming approvals and accepted-follower visibility checks.
CREATE INDEX follows_followee_status_idx
  ON public.follows (followee_id, status, requested_at DESC, id DESC);

-- Fast "following" feed membership and counts.
CREATE INDEX follows_follower_accepted_idx
  ON public.follows (follower_id, followee_id)
  WHERE status = 'accepted';

CREATE TABLE public.notifications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  recipient_user_id UUID NOT NULL,
  actor_user_id UUID,
  type VARCHAR(32) NOT NULL,
  -- The event key is generated by the Backend; a unique key prevents
  -- duplicate notifications on repeated API calls or retries.
  event_key VARCHAR(240) NOT NULL,
  post_id UUID,
  comment_id UUID,
  follow_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at TIMESTAMPTZ,

  CONSTRAINT notifications_recipient_fk
    FOREIGN KEY (recipient_user_id)
    REFERENCES public.users (id)
    ON DELETE CASCADE,

  CONSTRAINT notifications_actor_fk
    FOREIGN KEY (actor_user_id)
    REFERENCES public.users (id)
    ON DELETE SET NULL,

  CONSTRAINT notifications_post_fk
    FOREIGN KEY (post_id)
    REFERENCES public.posts (id)
    ON DELETE SET NULL,

  CONSTRAINT notifications_comment_fk
    FOREIGN KEY (comment_id)
    REFERENCES public.post_comments (id)
    ON DELETE SET NULL,

  CONSTRAINT notifications_follow_fk
    FOREIGN KEY (follow_id)
    REFERENCES public.follows (id)
    ON DELETE SET NULL,

  CONSTRAINT notifications_event_key_unique UNIQUE (event_key),

  CONSTRAINT notifications_type_check CHECK (
    type IN (
      'post_like',
      'post_comment',
      'comment_reply',
      'comment_like',
      'follow',
      'follow_request',
      'follow_accepted'
    )
  ),

  CONSTRAINT notifications_read_time_check CHECK (
    read_at IS NULL OR read_at >= created_at
  )
);

-- Inbox pagination by (created_at, id), newest first.
CREATE INDEX notifications_recipient_created_idx
  ON public.notifications (recipient_user_id, created_at DESC, id DESC);

-- Unread count / badge. The full list uses the index above.
CREATE INDEX notifications_recipient_unread_idx
  ON public.notifications (recipient_user_id, created_at DESC, id DESC)
  WHERE read_at IS NULL;

-- FK lookups for removing optional references without full table scans.
CREATE INDEX notifications_actor_idx
  ON public.notifications (actor_user_id)
  WHERE actor_user_id IS NOT NULL;

CREATE INDEX notifications_post_idx
  ON public.notifications (post_id)
  WHERE post_id IS NOT NULL;

CREATE INDEX notifications_comment_idx
  ON public.notifications (comment_id)
  WHERE comment_id IS NOT NULL;

CREATE INDEX notifications_follow_idx
  ON public.notifications (follow_id)
  WHERE follow_id IS NOT NULL;

COMMIT;
